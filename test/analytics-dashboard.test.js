  assert.match(admin, /uniqueVisits: row\.uniqueVisits \?\? row\.sessions/);
  assert.match(admin, /pageViews: row\.pageViews \|\| 0/);
  assert.match(admin, /mapLoads: row\.mapLoads \|\| 0/);
  assert.match(admin, /analyticsRollupError/);
  assert.match(admin, /\['Відкриття карти', 'mapLoads'/);
