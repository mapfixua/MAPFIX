const ROOT = path.join(__dirname, '..');

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

function pgBin(name) {
  for (const version of ['17', '18', '16']) {
    const candidate = `/usr/lib/postgresql/${version}/bin/${name}`;
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.listen(0, '127.0.0.1', () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
    server.on('error', reject);
  });
}

async function startCluster() {
  const initdb = pgBin('initdb');
  const pgCtl = pgBin('pg_ctl');
  if (!initdb || !pgCtl) return null;
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mapfix-pg-'));
  const port = await freePort();
  const init = spawnSync(
    initdb,
    ['-D', dir, '--username=postgres', '--auth=trust', '--no-sync', '--locale=C.UTF-8', '--encoding=UTF8'],
    { encoding: 'utf8' }
  );
  if (init.status !== 0) {
    fs.rmSync(dir, { recursive: true, force: true });
    throw new Error(init.stderr || init.stdout || 'initdb failed');
  }
  // pg_ctl -l keeps the server from inheriting this process's pipes. Without it,
  // spawnSync waits forever for stdout EOF held open by postgres.
  const logFile = path.join(dir, 'server.log');
  const started = spawnSync(
    pgCtl,
    [
      '-D',
      dir,
      '-w',
      '-t',
      '30',
      '-l',
      logFile,
      '-o',
      `-p ${port} -k ${dir} -c listen_addresses= -c unix_socket_directories=${dir}`,
      'start',
    ],
    { encoding: 'utf8', stdio: 'ignore' }
  );
  if (started.status !== 0) {
    const log = fs.existsSync(logFile) ? fs.readFileSync(logFile, 'utf8') : '';
    fs.rmSync(dir, { recursive: true, force: true });
    throw new Error(log || 'postgres failed to start');
  }
  return {
    dir,
    port,
    stop() {
      spawnSync(pgCtl, ['-D', dir, '-w', '-t', '20', '-m', 'immediate', 'stop'], { stdio: 'ignore' });
      fs.rmSync(dir, { recursive: true, force: true });
    },
  };
}

async function connect(dir, port) {
  let last;
  for (let i = 0; i < 30; i += 1) {
    const client = new Client({
      host: dir,
      port,
      user: 'postgres',
      database: 'postgres',
      connectionTimeoutMillis: 2000,
      statement_timeout: 15000,
      query_timeout: 15000,
    });
    try {
      await client.connect();
      return client;
    } catch (err) {
      last = err;
      try {
        await client.end();
      } catch (_) {
        /* socket was never opened */
      }
      await new Promise((resolve) => setTimeout(resolve, 100));
    }
  }
  throw last;
}

async function execFile(client, rel) {
  await client.query(read(rel));
}

