function main() {
  const raw = fs.readFileSync(DATA_FILE, 'utf8');
  const data = JSON.parse(raw);
  if (!data.masterCatalog || typeof data.masterCatalog !== 'object') {
    throw new Error('masterCatalog missing in data.json');
  }

  for (const [catKey, expansion] of Object.entries(EXPANSIONS)) {
    data.masterCatalog[catKey] = mergeCat(data.masterCatalog[catKey], expansion);
  }

  // Preferred category order
  const order = ['beauty', 'auto', 'repair', 'pets', 'home', 'education', 'sport', 'rental', 'medical'];
  const ordered = {};
  for (const key of order) {
    if (data.masterCatalog[key]) ordered[key] = data.masterCatalog[key];
  }
  for (const [key, val] of Object.entries(data.masterCatalog)) {
    if (!ordered[key]) ordered[key] = val;
  }
  data.masterCatalog = ordered;

  const validation = validateCatalogHierarchy(data.masterCatalog);
  if (!validation.ok) {
    console.error('Validation failed:');
    validation.errors.forEach((e) => console.error(' -', e));
    process.exit(1);
  }

  fs.writeFileSync(DATA_FILE, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log('Catalog expanded OK:', validation.stats);
}

main();
