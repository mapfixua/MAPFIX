function mergeSub(existing, incoming) {
  const out = existing && typeof existing === 'object' ? { ...existing } : { name: '', tags: [], items: [] };
  if (incoming.name) out.name = incoming.name;
  if (incoming.icon) out.icon = incoming.icon;
  const tagSet = new Set([...(out.tags || []), ...(incoming.tags || [])]);
  out.tags = [...tagSet];
  const byName = new Map((out.items || []).map((i) => [String(i.name).toLowerCase(), i]));
  for (const item of incoming.items || []) {
    const key = String(item.name).toLowerCase();
    if (!byName.has(key)) byName.set(key, item);
  }
  out.items = [...byName.values()];
  return out;
}

function mergeCat(existing, incoming) {
  const out = existing && typeof existing === 'object' ? { ...existing, subcats: { ...(existing.subcats || {}) } } : { name: '', icon: '📍', subcats: {} };
  if (incoming.name) out.name = incoming.name;
  if (incoming.icon) out.icon = incoming.icon;
  for (const [subKey, sub] of Object.entries(incoming.subcats || {})) {
    out.subcats[subKey] = mergeSub(out.subcats[subKey], sub);
  }
  return out;
}

